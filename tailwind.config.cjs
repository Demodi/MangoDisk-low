/**
 * Tailwind CSS v3 configuration for MangoDisk.
 *
 * Why v3: the app must render in the system WKWebView of macOS 10.15 Catalina
 * (Safari 15.6.1). Tailwind v4 requires Safari 16.4 because it registers
 * `--tw-*` custom properties with `@property` (16.4+) and builds every `/NN`
 * opacity utility with `color-mix()` (16.2+). Both are dropped wholesale by
 * Safari 15.6, which breaks dialog centring, selected-row colours and layout.
 * v3 emits plain `transform: translate(...)` and plain colour declarations.
 *
 * Safari 15.6.1 DOES support `oklch()` (15.4+), so semantic theme colours stay
 * in OKLCH with no sRGB gamut clipping. The `--<token>-ch` channel variables
 * are generated by scripts/generate-alpha-channels.mjs into
 * src/assets/themes/alpha-channels.css; keep that file regenerated whenever a
 * theme palette changes.
 */

/** Semantic colour token names, mirrored from the `@theme inline` block in
 *  src/assets/main.css and from alpha-channels.css. */
const colorTokens = [
  'background', 'workspace', 'foreground', 'card', 'card-foreground',
  'popover', 'popover-foreground', 'primary', 'primary-text',
  'primary-text-subtle', 'primary-text-hover', 'primary-foreground',
  'secondary', 'secondary-foreground', 'muted', 'muted-foreground',
  'accent', 'accent-foreground', 'destructive', 'destructive-text',
  'destructive-foreground', 'success', 'success-foreground', 'warning',
  'usage-warning', 'usage-critical', 'warning-foreground', 'border', 'input',
  'ring', 'sidebar', 'sidebar-foreground', 'sidebar-accent',
  'sidebar-accent-foreground', 'sidebar-border', 'chart-1', 'chart-2',
  'chart-3', 'chart-4', 'chart-5', 'file-code', 'file-audio', 'file-image',
  'file-data', 'file-package', 'file-binary',
];

const colors = Object.fromEntries(
  colorTokens.map((name) => [name, `oklch(var(--${name}-ch) / <alpha-value>)`]),
);

const fontTokens = [
  'content-empty-title', 'content-section-title', 'content-primary',
  'content-body', 'content-secondary', 'content-meta',
];
const fontSize = Object.fromEntries(
  fontTokens.map((name) => [name, `var(--font-${name})`]),
);

const plugin = require('tailwindcss/plugin');

/** @type {import('tailwindcss').Config} */
module.exports = {
  content: [
    './index.html',
    './floating-monitor.html',
    './tray-panel.html',
    './memory-settings.html',
    './src/**/*.{vue,js,ts,jsx,tsx,html}',
  ],
  // v4's `@custom-variant dark (&:where([data-theme='dark'], ...))` equivalent.
  darkMode: ['selector', '[data-theme="dark"]'],
  theme: {
    extend: {
      colors,
      fontSize,
      borderRadius: {
        sm: 'calc(var(--radius) - 4px)',
        md: 'calc(var(--radius) - 2px)',
        lg: 'var(--radius)',
        xl: 'calc(var(--radius) + 4px)',
      },
      // Class names that existed in v4 but not in v3's default scale.
      // Declaring them here avoids touching hundreds of component templates.
      ringWidth: { 3: '3px' },
      boxShadow: { xs: '0 1px 2px 0 rgb(0 0 0 / 0.05)' },
      opacity: { 12: '0.12', 38: '0.38' },
    },
  },
  plugins: [
    require('tailwindcss-animate'),
    // Tailwind v4 ships `aria-invalid:` as a core variant; v3 does not, so the
    // checkbox's invalid-ring classes (`aria-invalid:ring-*` and the stacked
    // `dark:aria-invalid:ring-*`) would silently drop. Re-register it.
    plugin(({ addVariant }) => {
      addVariant('aria-invalid', '&[aria-invalid="true"]');
    }),
  ],
};
